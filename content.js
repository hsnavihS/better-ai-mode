(() => {
  const CARD_ID = "better-ai-mode-card";
  const STREAM_PORT_NAME = "better-ai-mode-search";
  const HIDDEN_OVERVIEW_CLASS = "better-ai-mode-hidden-overview";
  const AI_OVERVIEW_CONTAINER_SELECTORS = [
    "div.YzCcne[data-mg-cp='YzCcne']",
    "div[jsname='dEwkXc']",
    ".hdzaWe",
    ".Kevs9",
    "[data-mcpr]",
    "[data-attrid*='ai_overview' i]",
    "[data-attrid*='generative' i]",
    "[data-snhf]",
    "#Odp5De",
    ".MjjYud"
  ];

  let activeQuery = "";
  let activeRequestId = 0;
  let activePort = null;
  let answerText = "";
  let answerState = "idle";
  let statusText = "";

  function getQuery() {
    return new URL(window.location.href).searchParams.get("q")?.trim() || "";
  }

  function getCardElements() {
    const card = document.getElementById(CARD_ID);
    return {
      card,
      answer: card?.querySelector(".gac-answer"),
      status: card?.querySelector(".gac-status")
    };
  }

  function parseColor(color) {
    const match = color.match(/rgba?\((\d+),\s*(\d+),\s*(\d+)(?:,\s*([\d.]+))?\)/);
    if (!match || match[4] === "0") return null;

    return {
      red: Number(match[1]),
      green: Number(match[2]),
      blue: Number(match[3])
    };
  }

  function getLuminance(color) {
    return (color.red * 299 + color.green * 587 + color.blue * 114) / 1000;
  }

  function updateCardTheme(card) {
    const pageElements = [
      document.querySelector("#search"),
      document.body,
      document.documentElement
    ].filter(Boolean);
    const backgroundStyle = pageElements
      .map((element) => getComputedStyle(element).backgroundColor)
      .find((color) => parseColor(color));
    const foregroundStyle = pageElements
      .map((element) => getComputedStyle(element).color)
      .find((color) => parseColor(color));
    const backgroundColor = parseColor(backgroundStyle || "");
    const foregroundColor = parseColor(foregroundStyle || "");
    const isDark = backgroundColor
      ? getLuminance(backgroundColor) < 128
      : foregroundColor && getLuminance(foregroundColor) > 128;

    card.dataset.theme = isDark ? "dark" : "light";
    card.style.setProperty(
      "--gac-background",
      backgroundStyle || (isDark ? "#202124" : "#fff")
    );
    card.style.setProperty(
      "--gac-foreground",
      foregroundStyle || (isDark ? "#e8eaed" : "#202124")
    );
  }

  function ensureCard() {
    const results = document.querySelector("#rso");
    if (!results || !activeQuery) return null;

    let { card } = getCardElements();

    if (!card) {
      card = document.createElement("section");
      card.id = CARD_ID;
      card.setAttribute("aria-label", "AI answer");

      const label = document.createElement("div");
      label.className = "gac-label";
      label.textContent = "AI answer";

      const answer = document.createElement("div");
      answer.className = "gac-answer";
      answer.setAttribute("aria-live", "polite");

      const status = document.createElement("div");
      status.className = "gac-status";
      status.setAttribute("role", "status");

      const footer = document.createElement("div");
      footer.className = "gac-footer";
      footer.textContent = "Generated by Better AI Mode";

      card.append(label, answer, status, footer);
    }

    if (results.firstElementChild !== card) {
      results.prepend(card);
    }

    updateCardTheme(card);
    return card;
  }

  function renderCard() {
    const card = ensureCard();
    if (!card) return;

    const answer = card.querySelector(".gac-answer");
    const status = card.querySelector(".gac-status");
    card.dataset.state = answerState;
    answer.textContent = answerText;
    status.textContent = statusText;
  }

  function removeCard() {
    document.getElementById(CARD_ID)?.remove();
  }

  function restoreAIOverview() {
    document.querySelectorAll(`.${HIDDEN_OVERVIEW_CLASS}`).forEach((element) => {
      element.classList.remove(HIDDEN_OVERVIEW_CLASS);
    });
  }

  function findAIOverviewContainer(label) {
    const results = document.querySelector("#rso");

    for (const selector of AI_OVERVIEW_CONTAINER_SELECTORS) {
      const container = label.closest(selector);
      if (!container) continue;
      if (container === results || container.contains(results)) continue;
      return container;
    }

    return null;
  }

  function findAIOverviewLabels() {
    const labels = [];
    const walker = document.createTreeWalker(
      document.body,
      NodeFilter.SHOW_TEXT
    );

    while (walker.nextNode()) {
      const textNode = walker.currentNode;
      if (textNode.nodeValue?.trim().toLowerCase() !== "ai overview") continue;
      if (textNode.parentElement) labels.push(textNode.parentElement);
    }

    return labels;
  }

  function hideAIOverview() {
    if (!activeQuery) return;
    if (document.querySelector(`.${HIDDEN_OVERVIEW_CLASS}`)) return;

    for (const label of findAIOverviewLabels()) {
      const container = findAIOverviewContainer(label);
      if (container) {
        container.classList.add(HIDDEN_OVERVIEW_CLASS);
        return;
      }
    }
  }

  function cancelActiveStream() {
    if (!activePort) return;

    try {
      activePort.postMessage({
        type: "cancel",
        requestId: activeRequestId
      });
    } finally {
      activePort.disconnect();
      activePort = null;
    }
  }

  function startSearch(query) {
    cancelActiveStream();
    restoreAIOverview();

    activeQuery = query;
    activeRequestId += 1;
    answerText = "";
    answerState = "loading";
    statusText = "Generating mock answer...";
    renderCard();

    const requestId = activeRequestId;
    const port = chrome.runtime.connect({ name: STREAM_PORT_NAME });
    activePort = port;

    port.onMessage.addListener((message) => {
      if (requestId !== activeRequestId || message.requestId !== requestId) return;

      if (message.type === "chunk") {
        answerText += message.chunk;
        answerState = "streaming";
        statusText = "Generating mock answer...";
      } else if (message.type === "complete") {
        answerState = "complete";
        statusText = "";
        activePort = null;
        port.disconnect();
      } else if (message.type === "error") {
        answerState = "error";
        statusText = message.message || "The mock answer could not be generated.";
        activePort = null;
        port.disconnect();
      }

      renderCard();
    });

    port.onDisconnect.addListener(() => {
      if (activePort === port) activePort = null;
      if (requestId !== activeRequestId || answerState === "complete" || answerState === "error") {
        return;
      }

      answerState = "interrupted";
      statusText = "Answer interrupted. Change or resubmit the search to try again.";
      renderCard();
    });

    port.postMessage({
      type: "search",
      requestId,
      query
    });
  }

  function syncPage() {
    const query = getQuery();

    if (!query) {
      cancelActiveStream();
      activeQuery = "";
      activeRequestId += 1;
      answerText = "";
      answerState = "idle";
      statusText = "";
      removeCard();
      restoreAIOverview();
      return;
    }

    if (query !== activeQuery) {
      startSearch(query);
    } else {
      renderCard();
    }

    hideAIOverview();
  }

  let scheduled = false;
  const scheduleSync = () => {
    if (scheduled) return;
    scheduled = true;
    requestAnimationFrame(() => {
      scheduled = false;
      syncPage();
    });
  };

  const observer = new MutationObserver(scheduleSync);
  observer.observe(document.documentElement, {
    childList: true,
    subtree: true
  });

  window.addEventListener("popstate", scheduleSync);
  window.addEventListener("beforeunload", cancelActiveStream);
  syncPage();
})();
