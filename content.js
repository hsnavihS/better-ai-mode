(() => {
  const CARD_ID = "better-ai-mode-card";
  const ANSWER = "Hello world";

  function renderCard() {
    const results = document.querySelector("#rso");
    if (!results) return;

    let card = document.getElementById(CARD_ID);

    if (!card) {
      card = document.createElement("section");
      card.id = CARD_ID;
      card.setAttribute("aria-label", "AI answer");

      const label = document.createElement("div");
      label.className = "gac-label";
      label.textContent = "AI answer";

      const answer = document.createElement("div");
      answer.className = "gac-answer";
      answer.textContent = ANSWER;

      const footer = document.createElement("div");
      footer.className = "gac-footer";
      footer.textContent = "Generated by Better AI Mode";

      card.append(label, answer, footer);
    }

    // Insert before the first organic result; do not alter Google's AI Overview.
    if (results.firstElementChild !== card) {
      results.prepend(card);
    }
  }

  let scheduled = false;
  const observer = new MutationObserver(() => {
    if (scheduled) return;
    scheduled = true;
    requestAnimationFrame(() => {
      scheduled = false;
      renderCard();
    });
  });

  function appendNoAI() {
    const url = new URL(window.location.href);
    const query = url.searchParams.get("q");

    if (!query || query.endsWith("-noai")) return;

    url.searchParams.set("q", `${query} -noai`);
    window.location.replace(url.toString());
  }

  appendNoAI();

  observer.observe(document.documentElement, {
    childList: true,
    subtree: true
  });

  renderCard();
})();
